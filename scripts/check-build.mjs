import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
const read=path=>readFileSync(new URL('../'+path,import.meta.url),'utf8');
const html=read('public/index.html');
assert.equal(html,read('public/download/index.html'),'Standalone file must match the published page');
assert(!/<script[^>]+src=/.test(html),'No external JavaScript');
assert(!/<link[^>]+rel="stylesheet"/.test(html),'No external stylesheets');
const fontUrls=[...html.matchAll(/url\('([^']+)'\)/g)].map(match=>match[1]);
assert.equal(fontUrls.length,3);assert(fontUrls.every(url=>url.startsWith('data:font/ttf;base64,')));
const ids=[...html.matchAll(/\bid="([^"]+)"/g)].map(match=>match[1]);
assert.equal(ids.length,new Set(ids).size,'Unique IDs');
for(const match of html.matchAll(/href="#([^"]+)"/g))assert(ids.includes(match[1]),'Valid anchor '+match[1]);
assert(html.includes('id="back-to-top"'));
assert(html.includes('type="email"'));
assert(html.includes('id="form-success"'));
assert(!/name="(?:email|phone|message)"/.test(html),'No native form data submission in demo');
assert(!/\b(?:fetch|XMLHttpRequest|sendBeacon)\s*\(/.test(read('src/app.js')),'Demo must not send messages');
const config=JSON.parse(read('vercel.json'));
assert.equal(config.outputDirectory,'public');assert.equal(config.framework,null);
assert.equal(JSON.parse(read('package.json')).engines.node,'24.x');
console.log('Build checks passed: standalone resources, anchors, demo privacy, Vercel configuration.');
